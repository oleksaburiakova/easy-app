/**
 * Кличний відмінок імені для звертання: «Доброго ранку, Олександро!».
 * Лише надійні правила; інакше — ім'я як є (краще «Катя», ніж помилка).
 *  - жіночі на приголосний + «а»: Олександра → Олександро, Олена → Олено, Ірина → Ірино;
 *  - на «ія»: Марія → Маріє, Наталія → Наталіє, Юлія → Юліє;
 *  - чоловічі на «ій»: Андрій → Андрію, Сергій → Сергію;
 *  - чоловічі на тверду приголосну (без «к/г/х»): Іван → Іване, Олександр → Олександре, Роман → Романе.
 */
export function vocative(raw: string): string {
  const name = raw.trim();
  if (!/^[А-ЯІЇЄҐа-яіїєґ'’-]{2,}$/.test(name)) return name;
  const lower = name.toLowerCase();
  const stem = (n: number) => name.slice(0, name.length - n);
  if (/ія$/.test(lower)) return stem(1) + 'є';
  if (/[бвдзлмнпрстфцчшщ]а$/.test(lower)) return stem(1) + 'о';
  if (/ій$/.test(lower)) return stem(1) + 'ю';
  if (/[бвдзлмнпрстф]$/.test(lower) && !/(ь|ей)$/.test(lower)) return name + 'е';
  return name;
}
