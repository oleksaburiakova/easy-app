/** Порада для кроку конструктора з урахуванням прийому їжі. */
export function stepHint(stepKey: string, meal: MealKey, idx: number): Hint | null {
  const list = (STEP_HINTS[stepKey] ?? []).filter((h) => !h.meals || h.meals.includes(meal));
  if (!list.length) return null;
  // На вечерю спершу — порада саме про вечерю.
  const own = list.findIndex((h) => h.meals?.includes(meal));
  return own >= 0 ? list[own] : list[(idx + (meal === 'lunch' ? 1 : 0)) % list.length];
}

export const pick = <T,>(arr: T[], seed = new Date().getDate()) => arr[seed % arr.length];
